#!/usr/bin/env node
// Measures how loud every sound in assets/audio is and writes src/game/00-audio-loudness.js.
// The game uses these numbers (see levelVolume in 00-audio-sfx-config.js) so every sound plays
// at the level of its tier, whatever level the file itself was recorded at.
// Run after adding or replacing any audio file:  pnpm run audio:levels
// Needs ffmpeg on the PATH.
"use strict";
const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");

const root = path.resolve(__dirname, "..");
const audioDir = path.join(root, "assets", "audio");
const outFile = path.join(root, "src", "game", "00-audio-loudness.js");
const EXT = new Set([".mp3", ".ogg", ".wav", ".m4a"]);

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) return walk(p);
    return EXT.has(path.extname(e.name).toLowerCase()) ? [p] : [];
  });
}

function measure(file) {
  // apad: a short sound still fills the 400 ms momentary window
  const r = spawnSync("ffmpeg", ["-hide_banner", "-nostats", "-v", "verbose", "-i", file, "-af", "apad=pad_dur=0.5,ebur128=framelog=verbose", "-f", "null", "-"], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  if (r.error) throw new Error("ffmpeg not found. Install ffmpeg and put it on the PATH, then run again.");
  const log = r.stderr || "";
  let peak = -120;
  for (const m of log.matchAll(/ M:\s*(-?[\d.]+)/g)) peak = Math.max(peak, Number(m[1]));
  const summary = log.slice(log.lastIndexOf("Summary:"));
  const integrated = Number((summary.match(/I:\s*(-?[\d.]+) LUFS/) || [])[1]);
  return { m: Math.round(peak * 10) / 10, i: Number.isFinite(integrated) ? Math.round(integrated * 10) / 10 : null };
}

const files = walk(audioDir).sort();
const lines = [];
for (const file of files) {
  const rel = path.relative(root, file).split(path.sep).join("/");
  const { m, i } = measure(file);
  lines.push(`  ${JSON.stringify(rel)}: { m: ${m}, i: ${i} }`);
  console.log(`${m.toFixed(1).padStart(6)}  ${String(i).padStart(6)}  ${rel}`);
}
const body = `"use strict";

// GENERATED by scripts/measure-audio.js. Do not edit by hand: run \`pnpm run audio:levels\`.
// m = loudest 400 ms of the file (LUFS, what the ear notices on a one-shot), i = integrated LUFS.
const AUDIO_LOUDNESS = {
${lines.join(",\n")}
};
`;
fs.writeFileSync(outFile, body);
console.log(`\nWrote ${path.relative(root, outFile)} (${files.length} files).`);
